import { keccak_256 } from '@noble/hashes/sha3';

/**
 * DB-08 (NEC-83): the durable-to-group receipt, checked on the client.
 *
 * Under `ddb-group-durable-ack` the leader can acknowledge a write as soon as an approve quorum of the epoch
 * committee has stored it (round 2) -- before the chain includes it. The acknowledgement is a
 * GroupDurableReceipt: every signer signed
 *
 *   GroupDurableDigest = keccak256("ddb-group-durable-v1" || networkId(8) || operationHash(32)
 *                                  || payloadHash(32) || ackTimeSec(8) || epoch(8))   (integers big-endian)
 *
 * with its ML-DSA-87 validator key. This module is the TS port of the node's check
 * (gossip/ddb/group_durable.go verifyGroupDurableQuorum): each signature a committee member's, no member
 * twice, the distinct-signer floor, and an approve quorum BY WEIGHT (floor(2/3 * total) + 1) -- the count
 * of signers only when the committee carries no weights. On top of that it checks what only the client
 * knows: the epoch whose committee it trusts, and (optionally) the operation it submitted.
 *
 * Cross-language vectors: tests/vectors/db08_receipt_vectors.json, generated by the node
 * (TestGroupDurableReceiptVectors) and judged identically by both suites.
 *
 * Where the committee comes from is the caller's trust decision. `Ddb.getDdbCommittee()` asks the node it is
 * talking to (ddb_getDdbValidators {committee:true}); a receipt checked against a committee served by the
 * same node that served the receipt proves only that node's view. Pin the committee from a node you trust.
 */

export const GROUP_DURABLE_DOMAIN = 'ddb-group-durable-v1';

type Bytesish = string | Uint8Array;
type Uintish = number | bigint | string;

export interface GroupDurableSignature {
  validator: string;
  signature: Bytesish;
}

/** ddb.GroupDurableReceipt (ethapi GroupDurableReceiptJSON): `ackTimeSec`/`epoch` as numbers or hex strings. */
export interface GroupDurableReceipt {
  operationHash: string;
  payloadHash: string;
  ackTimeSec: Uintish;
  epoch: Uintish;
  signatures: GroupDurableSignature[];
}

export interface DdbCommitteeMember {
  address: string;
  /** Raw ML-DSA-87 public key; address must be keccak256(publicKey)[12:]. */
  publicKey: Bytesish;
  /** Stake (vote) weight, decimal or hex. Absent for every member: the count-based threshold applies. */
  weight?: Uintish | null;
}

/** One epoch's DDB committee, as a receipt verifier needs it (ddb_getDdbValidators {committee:true}). */
export interface DdbCommittee {
  epoch: Uintish;
  networkId: Uintish;
  members: DdbCommitteeMember[];
  /** Count-based 2f+1, used only when no member carries a weight. */
  threshold?: number;
  /** SEC-01 distinct-signer floor; 0 / absent = none. */
  minSigners?: number;
}

export interface GroupDurableVerifyOptions {
  /** The operation hash you submitted; the receipt must name it. */
  operationHash?: string;
  /** The plain commit payload, when you hold it; keccak256(payload) must be the receipt's payloadHash. */
  payload?: Bytesish;
}

export interface GroupDurableVerdict {
  valid: boolean;
  /** Why not, when !valid. */
  reason?: string;
  /** Distinct verified signers. */
  signers: number;
  /** Their summed weight (0n for a count-based committee). */
  weight: bigint;
}

