// bytes
// ---------------------------------------------------------------------------

function hexToBytes(h: string): Uint8Array {
  let s = h.startsWith('0x') || h.startsWith('0X') ? h.slice(2) : h;
  if (s.length % 2 === 1) s = '0' + s;
  if (!/^[0-9a-fA-F]*$/.test(s)) throw new Error(`not hex: ${h.slice(0, 20)}`);
  const out = new Uint8Array(s.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(s.slice(2 * i, 2 * i + 2), 16);
  return out;
}

function toBytes(b: Bytesish): Uint8Array {
  return typeof b === 'string' ? hexToBytes(b) : b;
}

function bytesToHex(b: Uint8Array): string {
  let s = '0x';
  for (const x of b) s += x.toString(16).padStart(2, '0');
  return s;
}

function toBig(v: Uintish): bigint {
  if (typeof v === 'bigint') return v;
  if (typeof v === 'number') {
    if (!Number.isSafeInteger(v) || v < 0) throw new Error(`not a non-negative integer: ${v}`);
    return BigInt(v);
  }
  const b = BigInt(v); // "0x.." or decimal
  if (b < B0) throw new Error(`negative: ${v}`);
  return b;
}

function u64be(v: bigint): Uint8Array {
  if (v >= B1 << B64) throw new Error('does not fit in uint64');
  const out = new Uint8Array(8);
  for (let i = 7; i >= 0; i--) {
    out[i] = Number(v & BFF);
    v >>= B8;
  }
  return out;
}

function hash32(h: string, what: string): Uint8Array {
  const b = hexToBytes(h);
  if (b.length !== 32) throw new Error(`${what} is not 32 bytes`);
  return b;
}

const lc = (a: string) => a.toLowerCase();

// BigInt constants (the build targets ES2019, which has no bigint literals).
const B0 = BigInt(0), B1 = BigInt(1), B2 = BigInt(2), B3 = BigInt(3), B8 = BigInt(8), BFF = BigInt(0xff), B64 = BigInt(64);

/** GroupDurableDigest, byte for byte the node's. */
export function groupDurableDigest(networkId: Uintish, operationHash: string, payloadHash: string,
  ackTimeSec: Uintish, epoch: Uintish): Uint8Array {
  const dom = new TextEncoder().encode(GROUP_DURABLE_DOMAIN);
  const parts = [dom, u64be(toBig(networkId)), hash32(operationHash, 'operationHash'), hash32(payloadHash, 'payloadHash'),
    u64be(toBig(ackTimeSec)), u64be(toBig(epoch))];
  const buf = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
  let o = 0;
  for (const p of parts) {
    buf.set(p, o);
    o += p.length;
  }
  return keccak_256(buf);
}

// ---------------------------------------------------------------------------
// RLP (the receipt alone: [opHash, payloadHash, ackTimeSec, epoch, [[validator, signature], ...]])
// ---------------------------------------------------------------------------

type Rlp = Uint8Array | Rlp[];

function rlpItem(d: Uint8Array, p: number): [Rlp, number] {
  if (p >= d.length) throw new Error('rlp: unexpected end of input');
  const b = d[p];
  const len = (n: number, at: number) => {
    let l = 0;
    for (let i = 0; i < n; i++) l = l * 256 + d[at + i];
    return l;
  };
  let start: number, size: number, list: boolean;
  if (b <= 0x7f) return [d.slice(p, p + 1), p + 1];
  if (b <= 0xb7) [start, size, list] = [p + 1, b - 0x80, false];
  else if (b <= 0xbf) [start, size, list] = [p + 1 + (b - 0xb7), len(b - 0xb7, p + 1), false];
  else if (b <= 0xf7) [start, size, list] = [p + 1, b - 0xc0, true];
  else [start, size, list] = [p + 1 + (b - 0xf7), len(b - 0xf7, p + 1), true];
  const end = start + size;
  if (end > d.length) throw new Error('rlp: item runs past the input');
  if (!list) return [d.slice(start, end), end];
  const items: Rlp[] = [];
  for (let q = start; q < end;) {
    const [it, next] = rlpItem(d, q);
    items.push(it);
    q = next;
  }
  return [items, end];
}

function rlpUint(b: Rlp): bigint {
  if (!(b instanceof Uint8Array)) throw new Error('rlp: expected an integer');
  let v = B0;
  for (const x of b) v = (v << B8) | BigInt(x);
  return v;
}

function rlpBytes(b: Rlp): Uint8Array {
  if (!(b instanceof Uint8Array)) throw new Error('rlp: expected bytes');
  return b;
}

/** Decodes the receipt's RLP form (ddb_submitSignedOp's `groupDurableReceiptRlp`). */
export function decodeGroupDurableReceiptRlp(data: Bytesish): GroupDurableReceipt {
  const d = toBytes(data);
  const [top, end] = rlpItem(d, 0);
  if (end !== d.length) throw new Error('rlp: trailing bytes after the receipt');
  if (!Array.isArray(top) || top.length !== 5 || !Array.isArray(top[4])) throw new Error('rlp: not a group-durability receipt');
  return {
    operationHash: bytesToHex(rlpBytes(top[0])),
    payloadHash: bytesToHex(rlpBytes(top[1])),
    ackTimeSec: rlpUint(top[2]).toString(),
    epoch: rlpUint(top[3]).toString(),
    signatures: (top[4] as Rlp[]).map((s) => {
      if (!Array.isArray(s) || s.length !== 2) throw new Error('rlp: bad receipt signature');
      return { validator: bytesToHex(rlpBytes(s[0])), signature: bytesToHex(rlpBytes(s[1])) };
    }),
  };
}

/**
 * The committee from ddb_getDdbValidators' DB-08 view ({committee: true}): what {@link verifyGroupDurableReceipt}
 * takes. Throws when the result carries no committee (a node without DB-08, or the opt-in not sent).
 */
export function ddbCommitteeFromRpc(r: any): DdbCommittee {
  if (!r || !Array.isArray(r.committee)) throw new Error('this node does not serve the DB-08 committee view');
  return {
    epoch: r.epoch, networkId: r.networkId, threshold: r.threshold, minSigners: r.minSigners ?? 0,
    members: r.committee.map((m: any) => ({ address: m.address, publicKey: m.publicKey ?? '', weight: m.weight ?? undefined })),
  };
}

