// verification
// ---------------------------------------------------------------------------

let _mldsa: any = null;
async function getMldsa(): Promise<any> {
  if (_mldsa) return _mldsa;
  // @ts-ignore - noble-post-quantum.js is a bundled JS file without TypeScript declarations
  const noblePQ = (await import('./noble-post-quantum.js')) as any;
  const algorithms = noblePQ.default || noblePQ;
  _mldsa = algorithms.ml_dsa87;
  if (!_mldsa) throw new Error('ml_dsa87 not available in bundled noble-post-quantum');
  return _mldsa;
}

function addressOf(pub: Uint8Array): string {
  return bytesToHex(keccak_256(pub).slice(12));
}

/**
 * Verifies a group-durability receipt against the committee of the epoch you expect. Never throws for a
 * bad receipt: the verdict says why it is not valid. A receipt is valid only when ALL of these hold:
 *
 * - its epoch is `committee.epoch` (a receipt cannot be re-labelled to another epoch's committee);
 * - it names `opts.operationHash`, and signs keccak256(`opts.payload`), when those are given;
 * - every signature is a distinct committee member's valid ML-DSA-87 signature over the digest bound to
 *   `committee.networkId` (one bad or foreign signature fails the receipt, as on the node);
 * - at least `committee.minSigners` distinct signers, and their WEIGHT reaches floor(2/3 * total) + 1
 *   (the count-based `threshold` only when the committee carries no weights at all).
 */
export async function verifyGroupDurableReceipt(receipt: GroupDurableReceipt, committee: DdbCommittee,
  opts: GroupDurableVerifyOptions = {}): Promise<GroupDurableVerdict> {
  const no = (reason: string, signers = 0, weight = B0): GroupDurableVerdict => ({ valid: false, reason, signers, weight });
  let digest: Uint8Array;
  try {
    if (toBig(receipt.epoch) !== toBig(committee.epoch)) return no('receipt epoch is not the committee\'s');
    if (opts.operationHash !== undefined && lc(receipt.operationHash) !== lc(opts.operationHash)) {
      return no('receipt names a different operation');
    }
    if (opts.payload !== undefined && lc(bytesToHex(keccak_256(toBytes(opts.payload)))) !== lc(receipt.payloadHash)) {
      return no('receipt does not sign this payload');
    }
    digest = groupDurableDigest(committee.networkId, receipt.operationHash, receipt.payloadHash, receipt.ackTimeSec, receipt.epoch);
  } catch (e: any) {
    return no(`malformed receipt: ${e?.message ?? e}`);
  }

  const members = new Map<string, { pub: Uint8Array; weight: bigint | null }>();
  try {
    for (const m of committee.members) {
      members.set(lc(m.address), {
        pub: toBytes(m.publicKey ?? ''),
        weight: m.weight === undefined || m.weight === null ? null : toBig(m.weight),
      });
    }
  } catch (e: any) {
    return no(`malformed committee: ${e?.message ?? e}`);
  }
  if (!Array.isArray(receipt.signatures)) return no('malformed receipt: no signatures array');

  const mldsa = await getMldsa();
  const seen = new Set<string>();
  for (let i = 0; i < receipt.signatures.length; i++) {
    const s = receipt.signatures[i];
    const who = lc(s.validator);
    const m = members.get(who);
    if (!m || m.pub.length === 0) return no(`receipt signature ${i}: no committee pubkey for ${s.validator}`, seen.size);
    if (seen.has(who)) return no(`duplicate receipt signature from ${s.validator}`, seen.size);
    let ok = false;
    try {
      ok = addressOf(m.pub) === who && mldsa.verify(m.pub, digest, toBytes(s.signature));
    } catch {
      ok = false;
    }
    if (!ok) return no(`receipt signature ${i} does not verify for ${s.validator}`, seen.size);
    seen.add(who);
  }

  // The node's MeetsApproveQuorum: the floor first and in addition, then weight, else count.
  const minSigners = committee.minSigners ?? 0;
  if (minSigners > 0 && seen.size < minSigners) {
    return no(`receipt has ${seen.size} distinct signers, below the floor of ${minSigners}`, seen.size);
  }
  let total = B0;
  let weighted = false;
  for (const m of members.values()) {
    if (m.weight !== null) {
      weighted = true;
      total += m.weight;
    }
  }
  let got = B0;
  for (const a of seen) got += members.get(a)!.weight ?? B0;
  if (weighted && total > B0) {
    const quorum = (total * B2) / B3 + B1;
    if (got < quorum) return no(`receipt signers weigh ${got} of ${total}, below the approve quorum ${quorum}`, seen.size, got);
    return { valid: true, signers: seen.size, weight: got };
  }
  const threshold = committee.threshold;
  if (threshold === undefined || threshold <= 0) return no('committee carries neither weights nor a threshold', seen.size);
  if (seen.size < threshold) return no(`receipt has ${seen.size} signers, below the threshold ${threshold}`, seen.size);
  return { valid: true, signers: seen.size, weight: B0 };
}
