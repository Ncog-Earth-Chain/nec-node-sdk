function decodeWords(w: Uint8Array[]): ProviderRecordJSON {
  const [claim, key, op, auth, cap] = w;
  const u64 = (b: Uint8Array, from: number) => toBig(b.slice(from, from + 8));
  return {
    claimHash: bytesToHex(claim),
    keyHash: bytesToHex(key),
    operatorId: bytesToHex(op),
    auth: bytesToHex(auth.slice(12, 32)),
    expiry: Number(u64(auth, 4)),
    active: auth[3] !== 0,
    offered: '0x' + u64(cap, 24).toString(16),
    committed: '0x' + u64(cap, 16).toString(16),
  };
}

const lc = (s: string) => s.toLowerCase();
const normQty = (s: string) => '0x' + BigInt(s).toString(16);

/**
 * Verifies a resolver proof against `trustedStateRoot` (the stateRoot of the header of rootBlock from a header source
 * the caller trusts) for the records served. Never throws: a malformed proof is an invalid one.
 * An explicit registryCodeHash retains exclusive, case-insensitive caller-selected matching; without one, both
 * reviewed layout-compatible runtimes are supported. An override or valid verdict does not establish A4 suitability.
 */
export function verifyRegistryProof(
  trustedStateRoot: string, registry: string, proof: RegistryProofJSON | undefined | null, served: ServedProvider[],
  opts: { registryCodeHash?: string } = {},
): ProofVerdict {
  try {
    if (!proof || !proof.account) return { valid: false, reason: 'no proof attached' };
    const root = hexToBytes(trustedStateRoot);
    const accLeaf = verifyMptProof(root, keccak_256(hexToBytes(registry)), proof.account.accountProof.map(hexToBytes));
    if (accLeaf === null) return { valid: false, reason: 'the proof shows no registry account under the trusted root' };
    const acc = rlpDecode(accLeaf);
    if (!Array.isArray(acc) || acc.length !== 4) return { valid: false, reason: 'the proven account is malformed' };
    const [, , storageRoot, codeHash] = acc as Uint8Array[];
    const provenRuntime = bytesToHex(codeHash);
    if (opts.registryCodeHash != null
      ? lc(provenRuntime) !== lc(opts.registryCodeHash)
      : !isSupportedProviderRegistryRuntime(provenRuntime)) {
      return { valid: false, reason: 'the proven account is not the reviewed ProviderRegistry' };
    }
    const words = new Map<string, Uint8Array>();
    for (const sp of proof.account.storageProof) {
      const slot = word(BigInt(sp.key));
      const v = verifyMptProof(storageRoot, keccak_256(slot), sp.proof.map(hexToBytes));
      let raw: Uint8Array = new Uint8Array(0);
      if (v !== null) {
        const d = rlpDecode(v);
        if (Array.isArray(d)) return { valid: false, reason: 'a storage value is a list' };
        raw = d;
      }
      const w = new Uint8Array(32);
      w.set(raw, 32 - raw.length);
      words.set(bytesToHex(slot), w);
    }
    for (const p of served) {
      const base = providerSlot(p.validatorId);
      const w: Uint8Array[] = [];
      for (let i = 0; i < PROVIDER_WORDS; i++) {
        const x = words.get(bytesToHex(wordAt(base, i)));
        if (!x) return { valid: false, reason: `provider ${p.validatorId}: word ${i} is not proven` };
        w.push(x);
      }
      const got = decodeWords(w);
      const r = p.record;
      if (lc(got.claimHash) !== lc(r.claimHash) || lc(got.keyHash) !== lc(r.keyHash) || lc(got.operatorId) !== lc(r.operatorId) ||
        lc(got.auth) !== lc(r.auth) || got.expiry !== Number(r.expiry) || got.active !== r.active ||
        got.offered !== normQty(r.offered) || got.committed !== normQty(r.committed)) {
        return { valid: false, reason: `provider ${p.validatorId}: the proven record differs from the one served` };
      }
    }
    return { valid: true };
  } catch (e) {
    return { valid: false, reason: (e as Error).message };
  }
}

/** Verify stored booking words at a trusted sealed root, without proving collateral, activation, consent, key bindings or readiness. */
export function verifyPlacementProof(trustedStateRoot: string, contract: string, record: PlacementRecordJSON): ProofVerdict {
  try {
    const proof = record.proof;
    if (!proof?.account) throw new Error('no placement proof attached');
    if (!/^0x[0-9a-fA-F]{40}$/.test(contract) || !/^0x[0-9a-fA-F]{40}$/.test(record.manager)) throw new Error('invalid placement address');
    if (lc(proof.stateRoot) !== lc(trustedStateRoot) || lc(proof.account.address) !== lc(record.manager)) throw new Error('placement proof context differs');
    const leaf = verifyMptProof(hexToBytes(trustedStateRoot), keccak_256(hexToBytes(record.manager)), proof.account.accountProof.map(hexToBytes));
    if (leaf === null) throw new Error('no placement manager under the trusted root');
    const account = rlpDecode(leaf);
    if (!Array.isArray(account) || account.length !== 4 || account.some(Array.isArray)) throw new Error('malformed placement account');
    const [, , storageRoot, codeHash] = account as Uint8Array[];
    if (!isSupportedPlacementManagerRuntime(lc(bytesToHex(codeHash)))) throw new Error('not the reviewed PlacementManager runtime');
    const words = new Map<string, Uint8Array>();
    for (const sp of proof.account.storageProof) {
      const slotValue = BigInt(sp.key);
      if (slotValue < B0 || slotValue >= TWO256) throw new Error('invalid placement slot');
      const slot = word(slotValue);
      const encoded = verifyMptProof(storageRoot, keccak_256(slot), sp.proof.map(hexToBytes));
      const raw = encoded === null ? new Uint8Array(0) : rlpDecode(encoded);
      if (Array.isArray(raw) || raw.length > 32) throw new Error('invalid placement storage value');
      const padded = new Uint8Array(32);
      padded.set(raw, 32 - raw.length);
      words.set(bytesToHex(slot), padded);
    }
    const take = (slot: Uint8Array) => {
      const value = words.get(bytesToHex(slot));
      if (!value) throw new Error('placement word is not proven');
      return value;
    };
    const preimage = new Uint8Array(64);
    preimage.set(hexToBytes(contract), 12);
    preimage.set(word(BigInt(4)), 32); // mapping(address => Placement), storage slot 4
    const base = keccak_256(preimage);
    const packed = take(base);
    if (toBig(packed.slice(24)) !== BigInt(record.version) || toBig(packed.slice(16, 24)) !== BigInt(record.replicaBytes)) throw new Error('placement version or capacity differs');
    if (lc(bytesToHex(take(wordAt(base, 1)))) !== lc(record.groupHash)) throw new Error('placement group hash differs');
    const lengthSlot = wordAt(base, 2);
    const length = toBig(take(lengthSlot));
    if (length > BigInt(64) || length !== BigInt(record.members.length)) throw new Error('placement member count differs');
    const data = keccak_256(lengthSlot);
    const groupPreimage = new Uint8Array(record.members.length * 32);
    record.members.forEach((id, i) => {
      if (!Number.isInteger(id) || id <= 0 || id > 0xffffffff) throw new Error('invalid placement member');
      const value = take(wordAt(data, Math.floor(i / 8)));
      const offset = 28 - 4 * (i % 8);
      if (toBig(value.slice(offset, offset + 4)) !== BigInt(id)) throw new Error('placement member differs');
      groupPreimage.set(word(BigInt(id)), i * 32);
    });
    if (lc(bytesToHex(keccak_256(groupPreimage))) !== lc(record.groupHash)) throw new Error('placement members do not match group hash');
    return { valid: true };
  } catch (e) {
    return { valid: false, reason: (e as Error).message };
  }
}
