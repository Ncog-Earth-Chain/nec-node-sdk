import { keccak_256 } from '@noble/hashes/sha3';

/**
 * PLACE-02 phase B (NEC-93): the client's check of a proof-carrying resolver answer.
 *
 * `ddb_listProviders` / `ddb_providerHistory` / `ddb_resolveDatabase` with `{withProof: true}` attach
 * `eth_getProof`-shaped account and storage proofs of every provider record they serve, taken at the record's
 * `rootBlock` (never the head). This module verifies them against a state root the CALLER trusts -- the
 * `stateRoot` of the header of `rootBlock` fetched from a header source the user chose (owner ruling 35, Q1 (a)):
 *
 *   1. the account proof of the registry against that root (Merkle-Patricia, key keccak256(address));
 *   2. the account's code hash is the reviewed ProviderRegistry runtime's;
 *   3. each storage proof against the account's storage root (key keccak256(slot));
 *   4. the five words of every served record decode to exactly the record served.
 *
 * What a proof does NOT cover (Q2 (a)): the sealed consenting set and the host group are node-asserted; the
 * resolver client compares them across two nodes instead (ddb-resolve.ts).
 *
 * Cross-language vector: tests/vectors/place02_registry_proof.json, generated by the node
 * (ethapi TestRegistryProofVector): its sealed proof verifies, its head proof does not.
 */

/** keccak256 of the reviewed ProviderRegistry runtime (ddb/providerreg RuntimeCodeHash). */
export const PROVIDER_REGISTRY_RUNTIME_CODE_HASH = '0x0f31223eff41a809b03dbb72578191f3f227c4b3b4d9c11a21c16125c9f7aeff';

/** Storage layout the node reads (providerreg Slot* / ProviderWord*). */
export const REGISTRY_SLOT_ELIGIBILITY_FLOOR = 3;
export const REGISTRY_SLOT_PROVIDERS = 5;
export const PROVIDER_WORDS = 5;

export interface StorageProofJSON {
  key: string;
  value: string;
  proof: string[];
}

export interface AccountProofJSON {
  address: string;
  accountProof: string[];
  balance: string;
  codeHash: string;
  nonce: string;
  storageHash: string;
  storageProof: StorageProofJSON[];
}

export interface RegistryProofJSON {
  block: number;
  stateRoot: string;
  account: AccountProofJSON;
}

/** A provider record as the resolver serves it (RPCProviderRecord). */
export interface ProviderRecordJSON {
  claimHash: string;
  keyHash: string;
  operatorId: string;
  auth: string;
  expiry: number;
  active: boolean;
  offered: string;
  committed: string;
}

export interface ServedProvider {
  validatorId: number;
  record: ProviderRecordJSON;
}

export interface ProofVerdict {
  valid: boolean;
  reason?: string;
}

// ---------------------------------------------------------------------------
// bytes
// ---------------------------------------------------------------------------

function hexToBytes(h: string): Uint8Array {
  const s = h.startsWith('0x') || h.startsWith('0X') ? h.slice(2) : h;
  if (s.length % 2 !== 0 || !/^[0-9a-fA-F]*$/.test(s)) throw new Error(`not hex: ${h}`);
  const out = new Uint8Array(s.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(s.substr(i * 2, 2), 16);
  return out;
}

function bytesToHex(b: Uint8Array): string {
  let s = '0x';
  for (const x of b) s += x.toString(16).padStart(2, '0');
  return s;
}

function eq(a: Uint8Array, b: Uint8Array): boolean {
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return false;
  return true;
}

const B0 = BigInt(0), B8 = BigInt(8), BFF = BigInt(0xff), TWO256 = BigInt(1) << BigInt(256);

function word(v: bigint): Uint8Array {
  const out = new Uint8Array(32);
  let x = ((v % TWO256) + TWO256) % TWO256;
  for (let i = 31; i >= 0; i--) {
    out[i] = Number(x & BFF);
    x >>= B8;
  }
  return out;
}

function toBig(b: Uint8Array): bigint {
  let v = B0;
  for (const x of b) v = (v << B8) | BigInt(x);
  return v;
}

/** The first storage word of validatorId's record: keccak256(uint256(id) . uint256(5)). */
export function providerSlot(validatorId: number): Uint8Array {
  const buf = new Uint8Array(64);
  buf.set(word(BigInt(validatorId)), 0);
  buf.set(word(BigInt(REGISTRY_SLOT_PROVIDERS)), 32);
  return keccak_256(buf);
}

/** The slot n words after base. */
export function wordAt(base: Uint8Array, n: number): Uint8Array {
  return word(toBig(base) + BigInt(n));
}

// ---------------------------------------------------------------------------
// RLP and the Merkle-Patricia proof walk
// ---------------------------------------------------------------------------

type Rlp = Uint8Array | Rlp[];

function rlpItem(d: Uint8Array, p: number): [Rlp, number] {
  if (p >= d.length) throw new Error('rlp: unexpected end of input');
  const b = d[p];
  const len = (n: number, at: number) => {
    let l = 0;
    for (let i = 0; i < n; i++) l = l * 256 + d[at + i];
    return l;
  };
  let start: number, size: number, list: boolean;
  if (b <= 0x7f) return [d.slice(p, p + 1), p + 1];
  if (b <= 0xb7) [start, size, list] = [p + 1, b - 0x80, false];
  else if (b <= 0xbf) [start, size, list] = [p + 1 + (b - 0xb7), len(b - 0xb7, p + 1), false];
  else if (b <= 0xf7) [start, size, list] = [p + 1, b - 0xc0, true];
  else [start, size, list] = [p + 1 + (b - 0xf7), len(b - 0xf7, p + 1), true];
  const end = start + size;
  if (end > d.length) throw new Error('rlp: item runs past the input');
  if (!list) return [d.slice(start, end), end];
  const items: Rlp[] = [];
  for (let q = start; q < end;) {
    const [it, next] = rlpItem(d, q);
    items.push(it);
    q = next;
  }
  return [items, end];
}

function rlpDecode(d: Uint8Array): Rlp {
  const [it, end] = rlpItem(d, 0);
  if (end !== d.length) throw new Error('rlp: trailing bytes');
  return it;
}

function nibbles(key: Uint8Array): number[] {
  const out: number[] = [];
  for (const b of key) out.push(b >> 4, b & 0x0f);
  return out;
}

/** Hex-prefix decoding of a leaf / extension path: [nibbles, isLeaf]. */
function hexPrefix(enc: Uint8Array): [number[], boolean] {
  if (enc.length === 0) throw new Error('mpt: empty path');
  const flag = enc[0] >> 4;
  const n = nibbles(enc);
  const isLeaf = flag >= 2;
  const odd = (flag & 1) === 1;
  return [n.slice(odd ? 1 : 2), isLeaf];
}

/**
 * Walks a Merkle-Patricia proof from `root` along `key` (already hashed: the secure trie's path) and returns the
 * leaf's value, or null when the proof shows the key absent. Throws when the proof is not a proof under `root`
 * (a node whose hash is not the reference its parent holds, a malformed node).
 */
export function verifyMptProof(root: Uint8Array, key: Uint8Array, proof: Uint8Array[]): Uint8Array | null {
  const path = nibbles(key);
  let pos = 0;
  let expected: Uint8Array = root;
  let idx = 0;
  let node: Rlp | null = null;
  for (;;) {
    if (node === null) {
      if (idx >= proof.length) throw new Error('mpt: the proof ends before the path does');
      const enc = proof[idx++];
      if (!eq(keccak_256(enc), expected)) throw new Error(`mpt: proof node ${idx - 1} is not the node its parent references`);
      node = rlpDecode(enc);
    }
    if (!Array.isArray(node)) throw new Error('mpt: a node is not a list');
    let child: Rlp;
    if (node.length === 17) {
      if (pos === path.length) {
        const v = node[16];
        if (Array.isArray(v)) throw new Error('mpt: a branch value is a list');
        return v.length === 0 ? null : v;
      }
      child = node[path[pos++]];
    } else if (node.length === 2) {
      const p0 = node[0];
      if (Array.isArray(p0)) throw new Error('mpt: a path is a list');
      const [seg, isLeaf] = hexPrefix(p0);
      for (let i = 0; i < seg.length; i++) {
        if (path[pos + i] !== seg[i]) return null; // the path diverges: the key is absent
      }
      pos += seg.length;
      if (isLeaf) {
        if (pos !== path.length) return null;
        const v = node[1];
        if (Array.isArray(v)) throw new Error('mpt: a leaf value is a list');
        return v;
      }
      child = node[1];
    } else {
      throw new Error(`mpt: a node of ${node.length} items`);
    }
    if (Array.isArray(child)) {
      node = child; // an inline node (its encoding is under 32 bytes): no hash to check
      continue;
    }
    if (child.length === 0) return null;
    if (child.length !== 32) throw new Error('mpt: a child reference is neither a hash nor an inline node');
    expected = child;
    node = null;
  }
}

// ---------------------------------------------------------------------------
// the registry proof
// ---------------------------------------------------------------------------

function decodeWords(w: Uint8Array[]): ProviderRecordJSON {
  const [claim, key, op, auth, cap] = w;
  const u64 = (b: Uint8Array, from: number) => toBig(b.slice(from, from + 8));
  return {
    claimHash: bytesToHex(claim),
    keyHash: bytesToHex(key),
    operatorId: bytesToHex(op),
    auth: bytesToHex(auth.slice(12, 32)),
    expiry: Number(u64(auth, 4)),
    active: auth[3] !== 0,
    offered: '0x' + u64(cap, 24).toString(16),
    committed: '0x' + u64(cap, 16).toString(16),
  };
}

const lc = (s: string) => s.toLowerCase();
const normQty = (s: string) => '0x' + BigInt(s).toString(16);

/**
 * Verifies a resolver proof against `trustedStateRoot` (the stateRoot of the header of rootBlock from a header source
 * the caller trusts) for the records served. Never throws: a malformed proof is an invalid one.
 */
export function verifyRegistryProof(
  trustedStateRoot: string, registry: string, proof: RegistryProofJSON | undefined | null, served: ServedProvider[],
  opts: { registryCodeHash?: string } = {},
): ProofVerdict {
  try {
    if (!proof || !proof.account) return { valid: false, reason: 'no proof attached' };
    const root = hexToBytes(trustedStateRoot);
    const accLeaf = verifyMptProof(root, keccak_256(hexToBytes(registry)), proof.account.accountProof.map(hexToBytes));
    if (accLeaf === null) return { valid: false, reason: 'the proof shows no registry account under the trusted root' };
    const acc = rlpDecode(accLeaf);
    if (!Array.isArray(acc) || acc.length !== 4) return { valid: false, reason: 'the proven account is malformed' };
    const [, , storageRoot, codeHash] = acc as Uint8Array[];
    if (lc(bytesToHex(codeHash)) !== lc(opts.registryCodeHash ?? PROVIDER_REGISTRY_RUNTIME_CODE_HASH)) {
      return { valid: false, reason: 'the proven account is not the reviewed ProviderRegistry' };
    }
    const words = new Map<string, Uint8Array>();
    for (const sp of proof.account.storageProof) {
      const slot = word(BigInt(sp.key));
      const v = verifyMptProof(storageRoot, keccak_256(slot), sp.proof.map(hexToBytes));
      let raw: Uint8Array = new Uint8Array(0);
      if (v !== null) {
        const d = rlpDecode(v);
        if (Array.isArray(d)) return { valid: false, reason: 'a storage value is a list' };
        raw = d;
      }
      const w = new Uint8Array(32);
      w.set(raw, 32 - raw.length);
      words.set(bytesToHex(slot), w);
    }
    for (const p of served) {
      const base = providerSlot(p.validatorId);
      const w: Uint8Array[] = [];
      for (let i = 0; i < PROVIDER_WORDS; i++) {
        const x = words.get(bytesToHex(wordAt(base, i)));
        if (!x) return { valid: false, reason: `provider ${p.validatorId}: word ${i} is not proven` };
        w.push(x);
      }
      const got = decodeWords(w);
      const r = p.record;
      if (lc(got.claimHash) !== lc(r.claimHash) || lc(got.keyHash) !== lc(r.keyHash) || lc(got.operatorId) !== lc(r.operatorId) ||
        lc(got.auth) !== lc(r.auth) || got.expiry !== Number(r.expiry) || got.active !== r.active ||
        got.offered !== normQty(r.offered) || got.committed !== normQty(r.committed)) {
        return { valid: false, reason: `provider ${p.validatorId}: the proven record differs from the one served` };
      }
    }
    return { valid: true };
  } catch (e) {
    return { valid: false, reason: (e as Error).message };
  }
}
